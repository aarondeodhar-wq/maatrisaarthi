// Copies the signed release APK into public/ (served by the website for download)
// and records its version and size in src/core/appRelease.ts for the download buttons.
// Run via: npm run android:release
import { copyFileSync, readFileSync, statSync, writeFileSync } from 'node:fs';

const apk = 'android/app/build/outputs/apk/release/app-release.apk';
const target = 'public/maatrisaarthi.apk';

const gradle = readFileSync('android/app/build.gradle', 'utf8');
const version = (gradle.match(/versionName\s+"([^"]+)"/) || [])[1] || '1.0';
const sizeMb = (statSync(apk).size / (1024 * 1024)).toFixed(1);

copyFileSync(apk, target);
writeFileSync('src/core/appRelease.ts', `// Generated by scripts/publish-apk.mjs. Do not edit by hand.
export const APK_DOWNLOAD_URL = '/maatrisaarthi.apk';
export const APK_VERSION = '${version}';
export const APK_SIZE_LABEL = '${sizeMb} MB';
`);

console.log(`Published ${target} (v${version}, ${sizeMb} MB)`);
